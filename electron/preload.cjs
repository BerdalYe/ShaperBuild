// Bridge between the sandboxed renderer and the main process.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('native', {
  openDialog: (opts) => ipcRenderer.invoke('dialog:open', opts),
  saveDialog: (opts) => ipcRenderer.invoke('dialog:save', opts),
  readFile: (file) => ipcRenderer.invoke('fs:read', file),
  writeFile: (file, data) => ipcRenderer.invoke('fs:write', file, data),
  getRecent: () => ipcRenderer.invoke('recent:get'),
  addRecent: (file) => ipcRenderer.invoke('recent:add', file),
  clearRecent: () => ipcRenderer.invoke('recent:clear'),
  fileTimes: (files) => ipcRenderer.invoke('files:times', files),
  getFolders: () => ipcRenderer.invoke('folders:get'),
  chooseDesignsFolder: () => ipcRenderer.invoke('folders:choose'),
  showDesignsFolder: () => ipcRenderer.send('folders:show'),
  removeRecent: (file) => ipcRenderer.invoke('recent:remove', file),
  keepVersion: (file) => ipcRenderer.invoke('versions:keep', file),
  listVersions: (file) => ipcRenderer.invoke('versions:list', file),
  readVersion: (file, id) => ipcRenderer.invoke('versions:read', file, id),
  renameFile: (file, name) => ipcRenderer.invoke('file:rename', file, name),
  duplicateFile: (file) => ipcRenderer.invoke('file:duplicate', file),
  trashFile: (file) => ipcRenderer.invoke('file:trash', file),
  info: () => ipcRenderer.invoke('app:info'),
  writeRecovery: (data, meta) => ipcRenderer.invoke('recovery:write', data, meta),
  readRecovery: () => ipcRenderer.invoke('recovery:read'),
  clearRecovery: () => ipcRenderer.invoke('recovery:clear'),
  listSlicers: () => ipcRenderer.invoke('slicers:list'),
  drawingPDF: (opts) => ipcRenderer.invoke('drawing:pdf', opts),
  updateState: () => ipcRenderer.invoke('update:state'),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateInstall: () => ipcRenderer.invoke('update:install'),
  updateOpenPage: () => ipcRenderer.send('update:open-page'),
  onUpdateState: (cb) => ipcRenderer.on('update-state', (_e, s) => cb(s)),
  openForPrint: (opts) => ipcRenderer.invoke('print:open', opts),
  ready: () => ipcRenderer.send('app:ready'),
  setLanguage: (lang) => ipcRenderer.send('app:language', lang),
  setDirty: (dirty) => ipcRenderer.send('app:dirty', dirty),
  setTitle: (title) => ipcRenderer.send('app:title', title),
  setRepresentedFile: (file) => ipcRenderer.send('app:represented', file),
  closeConfirmed: () => ipcRenderer.send('app:close-confirmed'),
  showInFolder: (file) => ipcRenderer.send('shell:show', file),
  openUrl: (url) => ipcRenderer.send('shell:open-url', url),
  onMenu: (cb) => ipcRenderer.on('menu', (_e, command, arg) => cb(command, arg)),
  onOpenPath: (cb) => ipcRenderer.on('open-path', (_e, file) => cb(file)),
  // AI assistant: chat settings and turns (the key stays in the main
  // process), the MCP server for AI apps, and tool calls from those apps.
  aiSettings: () => ipcRenderer.invoke('ai:settings'),
  aiSave: (patch) => ipcRenderer.invoke('ai:save', patch),
  aiModels: () => ipcRenderer.invoke('ai:models'),
  aiChat: (req) => ipcRenderer.invoke('ai:chat', req),
  mcpState: () => ipcRenderer.invoke('mcp:state'),
  mcpSet: (enabled) => ipcRenderer.invoke('mcp:set', enabled),
  mcpNewToken: () => ipcRenderer.invoke('mcp:new-token'),
  mcpAddClaudeDesktop: () => ipcRenderer.invoke('mcp:add-claude-desktop'),
  onAiCall: (cb) => ipcRenderer.on('ai:call', (_e, id, name, input) => cb(id, name, input)),
  aiResult: (id, result) => ipcRenderer.send('ai:result', id, result),
  // Accounts and cloud designs (the login stays in the main process).
  cloud: {
    state: () => ipcRenderer.invoke('cloud:state'),
    signUp: (email, password) => ipcRenderer.invoke('cloud:sign-up', { email, password }),
    signIn: (email, password) => ipcRenderer.invoke('cloud:sign-in', { email, password }),
    google: () => ipcRenderer.invoke('cloud:google'),
    resetPassword: (email) => ipcRenderer.invoke('cloud:reset', { email }),
    confirmReset: (email, code, password) => ipcRenderer.invoke('cloud:confirm-reset', { email, code, password }),
    signOut: () => ipcRenderer.invoke('cloud:sign-out'),
    list: () => ipcRenderer.invoke('cloud:list'),
    save: (opts) => ipcRenderer.invoke('cloud:save', opts),
    open: (id) => ipcRenderer.invoke('cloud:open', { id }),
    rename: (id, name) => ipcRenderer.invoke('cloud:rename', { id, name }),
    remove: (id) => ipcRenderer.invoke('cloud:delete', { id }),
    deleteAccount: () => ipcRenderer.invoke('cloud:delete-account'),
  },
  pathSep: process.platform === 'win32' ? '\\' : '/',
  platform: process.platform,
});
